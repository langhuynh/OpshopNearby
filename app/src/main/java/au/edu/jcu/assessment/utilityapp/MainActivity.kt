@Composable
fun UtilityApp() {
    var selectedTab by remember { mutableStateOf("Utility") }
//    the ViewModels are shared between the screens, map and utility
    var shopVm: ShopViewModel = viewModel()
    Scaffold(
        bottomBar = {
            NavigationBar {
                NavigationBarItem(
                    icon = { Icon(Icons.Default.Home, contentDescription = "Utility") },
                    label = { Text("Utility") },
                    selected = selectedTab == "Utility",
                    onClick = {
                        shopVm.clearSelection()   // switching tabs closes an open shop
                        selectedTab = "Utility"
                    }
                )
                NavigationBarItem(
                    icon = { Icon(Icons.Default.LocationOn, contentDescription = "Map") },
                    label = { Text("Map") },
                    selected = selectedTab == "Map",
                    onClick = {
                        shopVm.clearSelection()
                        selectedTab = "Map"
                    }
                )
                NavigationBarItem(
                    icon = { Icon(Icons.Default.Settings, contentDescription = "Settings") },
                    label = { Text("Settings") },
                    selected = selectedTab == "Settings",
                    onClick = {
                        shopVm.clearSelection()
                        selectedTab = "Settings"
                    }
                )
            }
        }
    ) { innerPadding ->
        Box(modifier = Modifier.padding(innerPadding)) {
            when (selectedTab) {
                "Utility" -> UtilityScreen()
                "Settings" -> SettingsScreen()
            }
        }
    }
}